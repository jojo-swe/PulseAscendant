def write_wav(path, samples):
    """samples: float array (frames, 2) in full-scale units, written as stereo 48 kHz PCM16."""
    pcm = np.clip(np.round(np.asarray(samples) * 32767), -32768, 32767).astype('<i2')
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), 'wb') as out:
        out.setparams((2, 2, RATE, 0, 'NONE', 'not compressed'))
        out.writeframes(pcm.tobytes())


def read_wav(path):
    with wave.open(str(path), 'rb') as audio:
        return np.frombuffer(audio.readframes(audio.getnframes()), dtype='<i2').reshape(-1, 2) / 32768


def click_track(seconds, bpm=120, seed=0):
    """Decaying 1.8 kHz clicks on every beat over faint noise, the same in both channels."""
    rng = np.random.default_rng(seed)
    signal = rng.normal(0, .002, int(seconds * RATE))
    burst = np.arange(int(.03 * RATE))
    tone = .5 * np.sin(2 * np.pi * 1800 * burst / RATE) * np.exp(-burst / (.008 * RATE))
    for start in range(0, len(signal), int(60 / bpm * RATE)):
        signal[start:start + len(burst)] += tone[:len(signal) - start]
    return np.repeat(signal[:, None], 2, axis=1)


def array(text, name):
    match = re.search(r'\b' + name + r'\[[^\]]*\]\s*=\s*\{([^}]*)\}', text)
    if match is None:
        raise AssertionError(f'{name} not found')
    return [float(v) for v in match.group(1).replace('\n', '').split(',') if v.strip()]


class PipelineTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.root = Path(cls.temp.name)
        wav = cls.root / 'assets/music/placeholder.wav'
        wav.parent.mkdir(parents=True)
        subprocess.run([sys.executable, str(ROOT / 'tools/make_placeholder.py'), str(wav)],
                       check=True, capture_output=True)
        targets = ROOT / 'tools/show_targets_placeholder.json'
        result = subprocess.run([sys.executable, str(ROOT / 'tools/prepare_show.py'), '--root', str(cls.root),
                                 '--targets', str(targets), str(wav)], check=True, capture_output=True, text=True)
        cls.output = result.stdout
        generated = cls.root / 'src/show/generated'
        cls.headers = {name: (generated / f'{name}.hpp') for name in HEADERS}
        cls.targets = json.loads(targets.read_text())

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def receipt(self, name):
        return json.loads((self.root / 'music' / name).read_text())

    def test_headers_exist_in_the_generated_namespace(self):
        for name, path in self.headers.items():
            text = path.read_text()
            self.assertTrue(text.startswith('// Generated by tools/'), name)
            self.assertIn('namespace evo::show::generated {', text)

    def test_chapter_starts_land_on_tracked_beats_near_their_targets(self):
        cue = self.headers['cue_data'].read_text()
        starts = array(cue, 'chapterStarts')
        beats = array(self.headers['beat_data'].read_text(), 'beatTimes')
        targets = [c['target'] for c in self.targets['chapters']]
        self.assertEqual(len(starts), 11)
        self.assertEqual(starts[0], 0)
        self.assertTrue(all(b > a for a, b in zip(starts, starts[1:])), starts)
        self.assertLess(starts[-1], 270 - 5)
        for start, target in zip(starts[1:], targets[1:]):
            self.assertLessEqual(abs(start - target), 2.5, (start, target))
            self.assertLessEqual(min(abs(start - b) for b in beats), .001, start)

    def test_chapter_targets_mirror_the_authored_targets(self):
        cue = self.headers['cue_data'].read_text()
        self.assertEqual(array(cue, 'chapterTargets'), [c['target'] for c in self.targets['chapters']])
        self.assertIn('chapterCount = 11', cue)
        digest = self.receipt('show-audio.json')['sha256']
        self.assertIn(f'sourceSha256 = "{digest}"', cue)

    def test_beat_grid_measures_the_placeholder_tempo(self):
        beats = self.receipt('beats.json')
        self.assertAlmostEqual(beats['bpm_median'], 134, delta=1)
        self.assertAlmostEqual(beats['tracks'][0]['bpm_median'], 134, delta=1)

    def test_show_audio_receipt(self):
        show = self.receipt('show-audio.json')
        self.assertEqual(show['frames'], 12_960_000)
        self.assertEqual(show['track_start_frames'], [0])
        self.assertEqual(show['runtime_file'], 'assets/music/show.wav')
        for name in ('analysis.json', 'reactivity.json', 'direction.json'):
            self.assertTrue((self.root / 'music' / name).is_file(), name)

    def test_per_track_tables_cover_the_whole_track(self):
        music = self.headers['music_data'].read_text()
        self.assertEqual(array(music, 'trackFrames'), [12_960_000])
        self.assertEqual(array(music, 'envelopeOffsets'), [0, 5400])
        self.assertEqual(len(array(music, 'envelope')), 5400 * 3)
        self.assertEqual(len(array(music, 'spectrum')), 5400 * 24)
        reactivity = self.headers['reactivity_data'].read_text()
        self.assertEqual(array(reactivity, 'reactivityOffsets'), [0, 27000])
        self.assertEqual(len(array(reactivity, 'reactivity')), 27000 * 4)
        beat = self.headers['beat_data'].read_text()
        offsets = array(beat, 'beatOffsets')
        self.assertEqual(len(array(beat, 'beatTimes')), offsets[-1])
        self.assertEqual(len(array(beat, 'beatBar')), offsets[-1])


class MultiTrackTests(unittest.TestCase):
    """Two 30 s click tracks and three chapters, the last pinned to the second track's start."""

    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.root = Path(cls.temp.name)
        tracks = [cls.root / 'in/first.wav', cls.root / 'in/second.wav']
        for seed, track in enumerate(tracks):
            write_wav(track, click_track(30, seed=seed))
        targets = cls.root / 'targets.json'
        targets.write_text(json.dumps(dict(max_chapter_seconds=40, chapters=[
            dict(title='ONE', target=0, track=0), dict(title='TWO', target=12, track=0),
            dict(title='THREE', target=30, track=1)])))
        subprocess.run([sys.executable, str(ROOT / 'tools/prepare_show.py'), '--root', str(cls.root),
                        '--targets', str(targets), *map(str, tracks)], check=True, capture_output=True, text=True)
        cls.generated = cls.root / 'src/show/generated'

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def header(self, name):
        return (self.generated / f'{name}.hpp').read_text()

    def test_each_track_starts_its_first_chapter_exactly(self):
        starts = array(self.header('cue_data'), 'chapterStarts')
        self.assertEqual(len(starts), 3)
        self.assertEqual(starts[0], 0)
        self.assertLessEqual(abs(starts[1] - 12), 2.5)
        self.assertEqual(starts[2], 30.0)
        direction = json.loads((self.root / 'music/direction.json').read_text())
        self.assertEqual([t['start_seconds'] for t in direction['tracks']], [0, 30.0])
        self.assertEqual(direction['chapters'][2]['start'], 30.0)

    def test_offset_arrays_have_one_entry_per_track_plus_one(self):
        self.assertEqual(array(self.header('music_data'), 'trackFrames'), [30 * RATE] * 2)
        for header, name in (('music_data', 'envelopeOffsets'), ('reactivity_data', 'reactivityOffsets'),
                             ('beat_data', 'beatOffsets')):
            offsets = array(self.header(header), name)
            self.assertEqual(len(offsets), 3, name)
            self.assertEqual(offsets[0], 0, name)
            self.assertLess(offsets[0], offsets[1], name)
            self.assertLess(offsets[1], offsets[2], name)
        show = json.loads((self.root / 'music/show-audio.json').read_text())
        self.assertEqual(show['track_start_frames'], [0, 30 * RATE])
        self.assertEqual(show['frames'], 60 * RATE)


class JoinFadeTests(unittest.TestCase):
    """concatenate() fades each act join so show.wav does not click where one track meets the next."""

    def test_the_join_no_longer_steps_and_the_length_is_kept(self):
        t = np.arange(RATE // 2) / RATE
        hum = .05 * np.sin(2 * np.pi * 100 * t)[:, None]
        first, second = .2 + hum, -.2 + hum  # meeting head to tail they would jump by about 0.4
        self.assertGreaterEqual(abs(first[-1, 0] - second[0, 0]), .2)
        with tempfile.TemporaryDirectory() as temp:
            paths = [Path(temp) / 'first.wav', Path(temp) / 'second.wav', Path(temp) / 'show.wav']
            write_wav(paths[0], np.repeat(first, 2, axis=1))
            write_wav(paths[1], np.repeat(second, 2, axis=1))
            prepare_show.concatenate(paths[:2], paths[2])
            show, originals = read_wav(paths[2]), [read_wav(p) for p in paths[:2]]
        join, window = len(originals[0]), int(.005 * RATE)
        self.assertEqual(len(show), len(originals[0]) + len(originals[1]))
        steps = np.abs(np.diff(show[join - window:join + window], axis=0))
        self.assertLess(steps.max(), .02)
        # Only the 3 ms either side of the join changes: the show still starts and ends as the tracks do.
        fade = prepare_show.JOIN_FADE_FRAMES
        np.testing.assert_array_equal(show[:join - fade], originals[0][:-fade])
        np.testing.assert_array_equal(show[join + fade:], originals[1][fade:])


