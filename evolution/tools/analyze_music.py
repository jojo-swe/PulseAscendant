"""Generate deterministic 20 Hz envelopes and 24 log-spaced FFT bands. No BPM assumption.

Any number of tracks on the command line: one header for all of them in the evo::show::generated namespace,
with per-track offsets, and one receipt.

Usage: python3 tools/analyze_music.py [--header H] [--receipt R] <track1.wav> [<track2.wav> ...]
"""
import argparse
import hashlib
import json
import sys
import wave
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]

BAND_EDGES = np.geomspace(35, 18000, 25)


def spectrum_envelopes(mono, sample_rate):
    hop, size = sample_rate // 20, 8192
    window = np.hanning(size)
    frequencies = np.fft.rfftfreq(size, 1 / sample_rate)
    masks = [(frequencies >= low) & (frequencies < high) for low, high in zip(BAND_EDGES[:-1], BAND_EDGES[1:])]
    padded = np.pad(mono, (size // 2, size))
    levels = []
    for start in range(0, len(mono), hop):
        power = np.abs(np.fft.rfft(padded[start:start + size] * window)) ** 2
        levels.append([np.sqrt(power[mask].mean()) if mask.any() else 0 for mask in masks])
    levels = np.asarray(levels)
    # A common floor stops nearly silent bands from being amplified into false activity.
    per_band = np.percentile(levels, 95, axis=0)
    reference = max(1e-5, float(per_band.max()))
    scale = np.maximum(per_band, reference * .1)
    levels = np.clip(levels / scale, 0, 1)
    for i in range(1, len(levels)):
        speed = np.where(levels[i] > levels[i-1], .8, .38)
        levels[i] = levels[i-1] + speed * (levels[i] - levels[i-1])
    return levels


def analyze(path):
    blocks = []
    with wave.open(str(path), 'rb') as audio:
        if (audio.getframerate(), audio.getnchannels(), audio.getsampwidth()) != (48000, 2, 2):
            raise ValueError('Expected stereo 48 kHz PCM16')
        frames = audio.getnframes()
        while chunk := audio.readframes(48000):
            stereo = np.frombuffer(chunk, '<i2').reshape(-1, 2)
            blocks.append((stereo.astype(np.float32).mean(axis=1) / 32768).copy())
    full_mono = np.concatenate(blocks)
    frequency_bands = spectrum_envelopes(full_mono, 48000)
    mono = full_mono[::3]
    hop, window_size = 800, 2048
    window = np.hanning(window_size)
    frequency = np.fft.rfftfreq(window_size, 1 / 16000)
    bass_mask = (frequency >= 35) & (frequency <= 180)
    flux_mask = (frequency >= 80) & (frequency <= 5000)
    padded = np.pad(mono, (window_size // 2, window_size))
    energy, bass, flux = [], [], []
    previous = np.zeros(window_size // 2 + 1)
    for start in range(0, len(mono), hop):
        x = padded[start:start + window_size]
        spectrum = np.abs(np.fft.rfft(x * window))
        energy.append(np.sqrt(np.mean(x * x)))
        bass.append(np.sqrt(np.mean(spectrum[bass_mask] ** 2)))
        flux.append(np.maximum(spectrum - previous, 0)[flux_mask].mean())
        previous = spectrum

    def normalized(values, percentile=95):
        values = np.asarray(values)
        return np.clip(values / max(1e-7, np.percentile(values, percentile)), 0, 1)

    energy, bass = normalized(energy), normalized(bass)
    flux = np.asarray(flux)
    novelty = np.maximum(0, flux - np.convolve(flux, np.ones(21) / 21, 'same') * .7)
    novelty = normalized(novelty, 98)
    hits = np.zeros_like(novelty)
    last = -10
    for i in range(1, len(novelty) - 1):
        if novelty[i] > .25 and novelty[i] >= novelty[i - 1] and novelty[i] > novelty[i + 1] and i - last >= 5:
            hits[i] = novelty[i]
            last = i
    for i in range(1, len(hits)):
        hits[i] = max(hits[i], hits[i - 1] * .68)
    # Byte quantization keeps the embedded show data compact and cross-platform.
    data = np.rint(np.stack((energy, bass, hits), axis=1) * 255).astype(np.uint8)
    return frames, data, np.rint(frequency_bands * 255).astype(np.uint8)


def track_report(path, frames, data):
    return dict(source=Path(path).name, frames=frames, duration=frames/48000, envelope_samples=len(data),
                transient_peaks=int(((data[:, 2] > 64) & (np.r_[0, data[:-1, 2]] < data[:, 2])).sum()),
                runtime_sha256=hashlib.sha256(Path(path).read_bytes()).hexdigest())


def write_outputs(paths, results, header_path, receipt_path):
    """results: analyze() output per track, in show order."""
    count = len(results)
    offsets = [0]
    for _, data, _ in results:
        offsets.append(offsets[-1] + len(data))
    data = np.concatenate([r[1] for r in results])
    spectrum = np.concatenate([r[2] for r in results])
    if len(spectrum) != len(data):
        raise ValueError('Envelope and spectrum sample counts differ')
    rows = [','.join(map(str, row.flatten())) for row in np.array_split(data, max(1, len(data) // 16))]
    spectrum_rows = [','.join(map(str, row)) for row in spectrum]
    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text('// Generated by tools/analyze_music.py; source facts in music/analysis.json.\n'
                           '#pragma once\n#include <cstdint>\nnamespace evo::show::generated {\n'
                           f'inline constexpr int trackCount = {count};\n'
                           f'inline constexpr std::uint64_t trackFrames[{count}] = {{'
                           + ','.join(str(r[0]) for r in results) + '};\n'
                           'inline constexpr int envelopeRate = 20, bands = 24;\n'
                           '// envelopeOffsets[i] is track i\'s first 20 Hz sample; the last entry is the total.\n'
                           f'inline constexpr int envelopeOffsets[{count + 1}] = {{' + ','.join(map(str, offsets))
                           + '};\n'
                           '// 3 bytes per sample: energy, bass, hit.\n'
                           'inline constexpr std::uint8_t envelope[] = {\n' + ',\n'.join(rows) + '\n};\n'
                           '// 24 bytes per sample, one per log-spaced band.\n'
                           'inline constexpr std::uint8_t spectrum[] = {\n' + ',\n'.join(spectrum_rows)
                           + '\n};\n}\n', encoding='utf-8')
    report = dict(envelope_rate=20, spectrum_bands=24, spectrum_edges_hz=BAND_EDGES.round(3).tolist(),
                  spectrum_method='48 kHz / 8192 sample centred Hann FFT; log-spaced 35-18000 Hz bands; attack/release; interpolated at playback clock',
                  method='RMS, 35-180 Hz bass, positive spectral flux; 2048 sample Hann / 16 kHz; no assumed beat grid',
                  envelope_offsets=offsets,
                  tracks=[track_report(path, frames, data) for path, (frames, data, _) in zip(paths, results)])
    receipt_path.parent.mkdir(parents=True, exist_ok=True)
    receipt_path.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('tracks', nargs='+', type=Path, help='stereo 48 kHz PCM16 WAV files, in show order')
    parser.add_argument('--header', type=Path, default=ROOT / 'src/show/generated/music_data.hpp')
    parser.add_argument('--receipt', type=Path, default=ROOT / 'music/analysis.json')
    args = parser.parse_args()
    report = write_outputs(args.tracks, [analyze(path) for path in args.tracks], args.header, args.receipt)
    json.dump(report['tracks'], sys.stdout)
    print()


if __name__ == '__main__':
    main()
