constexpr int kGlyphsPerBlock = 8;
constexpr std::size_t kLineLength = kGlyphsPerBlock * 9 - 1; // eight 8-pixel glyphs and the spaces between
static_assert(std::size(kSheet) == kGlyphCount * 8 / kGlyphsPerBlock, "one block of 8 rows per 8 glyphs");

constexpr bool sheetIsWellFormed() {
    for (const char* line : kSheet) {
        std::size_t length = 0;
        for (; line[length] != '\0'; ++length) {
            const char c = line[length];
            const bool separator = length % 9 == 8;
            if (separator ? c != ' ' : (c != '#' && c != '.'))
                return false;
        }
        if (length != kLineLength)
            return false;
    }
    return true;
}
static_assert(sheetIsWellFormed(), "every sheet line is eight 8-character glyph rows of '#' and '.'");

constexpr std::array<GlyphRows, kGlyphCount> parseSheet() {
    std::array<GlyphRows, kGlyphCount> glyphs{};
    for (int index = 0; index < kGlyphCount; ++index) {
        const int block = index / kGlyphsPerBlock, column = index % kGlyphsPerBlock;
        for (int row = 0; row < 8; ++row) {
            const char* line = kSheet[block * 8 + row] + column * 9;
            std::uint8_t bits = 0;
            for (int x = 0; x < 8; ++x)
                if (line[x] == '#')
                    bits |= static_cast<std::uint8_t>(0x80u >> x);
            glyphs[index][row] = bits;
        }
    }
    return glyphs;
}

constexpr std::array<GlyphRows, kGlyphCount> kGlyphs = parseSheet();

// The code point of the UTF-8 sequence at text[i], advancing i past it; -1 for a malformed sequence (i then
// moves past its first byte only).
long decode(std::string_view text, std::size_t& i) {
    const auto byte = [&](std::size_t at) { return static_cast<unsigned char>(text[at]); };
    const unsigned char lead = byte(i);
    int length = 0;
    long codePoint = 0;
    if (lead < 0x80) {
        ++i;
        return lead;
    } else if ((lead & 0xE0) == 0xC0) {
        length = 2;
        codePoint = lead & 0x1F;
    } else if ((lead & 0xF0) == 0xE0) {
        length = 3;
        codePoint = lead & 0x0F;
    } else if ((lead & 0xF8) == 0xF0) {
        length = 4;
        codePoint = lead & 0x07;
    } else {
        ++i;
        return -1;
    }
    if (i + length > text.size()) {
        ++i;
        return -1;
    }
    for (int k = 1; k < length; ++k) {
        if ((byte(i + k) & 0xC0) != 0x80) {
            ++i;
            return -1;
        }
        codePoint = codePoint << 6 | (byte(i + k) & 0x3F);
    }
    i += length;
    return codePoint;
}

