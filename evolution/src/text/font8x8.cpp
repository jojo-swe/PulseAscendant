const GlyphRows& glyph(char code) {
    const auto c = static_cast<unsigned char>(code);
    if (c < kFirstGlyph || c > kMiddleDot)
        return kGlyphs['?' - kFirstGlyph];
    return kGlyphs[c - kFirstGlyph];
}

std::vector<std::uint8_t> glyphCodes(std::string_view utf8) {
    std::vector<std::uint8_t> codes;
    codes.reserve(utf8.size());
    for (std::size_t i = 0; i < utf8.size();) {
        const long codePoint = decode(utf8, i);
        if (codePoint == '\n' || (codePoint >= kFirstGlyph && codePoint < kMiddleDot)) {
            codes.push_back(static_cast<std::uint8_t>(codePoint));
        } else if (codePoint == 0xB7) { // MIDDLE DOT
            codes.push_back(kMiddleDot);
        } else if (codePoint == 0xD7) { // MULTIPLICATION SIGN
            codes.push_back('x');
        } else if (codePoint == 0x2192) { // RIGHTWARDS ARROW
            codes.push_back('-');
            codes.push_back('>');
        } else {
            codes.push_back('?');
        }
    }
    return codes;
}

int textWidth(std::string_view utf8, int scale) {
    int widest = 0, line = 0;
    for (std::uint8_t code : glyphCodes(utf8)) {
        line = code == '\n' ? 0 : line + 1;
        widest = std::max(widest, line);
    }
    return widest * 8 * scale;
}

