"""Extract sharp, frequency-specific motion triggers at 100 Hz from the actual PCM.

The existing 20 Hz analysis remains the editorial/cue source. This second layer
separates sustained loudness from attacks, so a mastered loud song does not pin
every animation at its maximum. No synthetic metronome or assumed BPM is used.
"""
import hashlib
import json
from pathlib import Path
import wave

import numpy as np

RATE = 100
CHANNELS = ((35, 180), (180, 4000), (4000, 18000))
RELEASE = (.16, .095, .055)
REFRACTORY = (.16, .11, .07)


def extract(mono, sample_rate=48000):
    hop, size = sample_rate // RATE, 2048
    window = np.hanning(size)
    frequencies = np.fft.rfftfreq(size, 1 / sample_rate)
    masks = [(frequencies >= lo) & (frequencies < hi) for lo, hi in CHANNELS]
    padded = np.pad(mono, (size // 2, size))
    count = (len(mono) + hop - 1) // hop
    flux = np.zeros((count, 3))
    previous = np.zeros(size // 2 + 1)
    for i, start in enumerate(range(0, len(mono), hop)):
        spectrum = np.abs(np.fft.rfft(padded[start:start + size] * window))
        increase = np.maximum(spectrum - previous, 0)
        flux[i] = [np.sqrt(np.mean(increase[m] ** 2)) for m in masks]
        previous = spectrum
    values = np.zeros((count, 4))
    reference = float(np.percentile(flux, 99, axis=0).max())
    peaks = []
    for channel, (release, refractory) in enumerate(zip(RELEASE, REFRACTORY)):
        signal = flux[:, channel]
        # A relative local floor suppresses continuous textures. An absolute
        # floor also keeps digital silence / numerical noise from becoming hits.
        local = np.convolve(np.pad(signal, (20, 20), mode='edge'), np.ones(41) / 41, 'valid')
        novelty = np.maximum(signal - local * .72, 0)
        scale = max(.04, reference * (.06, .04, .012)[channel], float(np.percentile(novelty, 98)))
        strength = np.clip(novelty / scale, 0, 1)
        candidates = np.flatnonzero((strength > (.25, .4, .32)[channel]) &
                                    (strength >= np.r_[0, strength[:-1]]) &
                                    (strength > np.r_[strength[1:], 0]))
        selected = []
        # Keep the stronger event when two nearby FFT peaks describe one hit.
        for i in candidates:
            if selected and i - selected[-1] < round(refractory * RATE):
                if strength[i] > strength[selected[-1]]:
                    selected[-1] = int(i)
            else:
                selected.append(int(i))
        peaks.append(selected)
        values[selected, channel] = strength[selected] ** .72
        decay = np.exp(-1 / (RATE * release))
        for i in range(1, count):
            values[i, channel] = max(values[i, channel], values[i-1, channel] * decay)
    # Measured low-band onset phase, not a guessed beat grid. During long gaps
    # phase settles at1; it never manufactures a pulse in silence.
    for j, start in enumerate(peaks[0]):
        end = peaks[0][j+1] if j+1 < len(peaks[0]) else count
        interval = min(end-start, RATE * 1.2)
        values[start:end, 3] = np.minimum(np.arange(end-start) / max(1, interval), 1)
    return np.rint(values * 255).astype(np.uint8), peaks


def main():
    root = Path(__file__).resolve().parents[1]
    sources = ('luminous-flow-act1.wav', 'adventurous-uplift.wav', 'rigid-arpeggios.wav')
    data, reports, offsets = [], [], [0]
    for source in sources:
        path = root / 'assets/music' / source
        with wave.open(str(path), 'rb') as audio:
            assert (audio.getframerate(), audio.getnchannels(), audio.getsampwidth()) == (48000, 2, 2)
            pcm = audio.readframes(audio.getnframes())
        mono = np.frombuffer(pcm, '<i2').reshape(-1, 2).astype(np.float32).mean(axis=1) / 32768
        values, peaks = extract(mono)
        data.append(values)
        offsets.append(offsets[-1] + len(values))
        reports.append(dict(source=source, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                            samples=len(values), peaks=[len(p) for p in peaks],
                            active_fraction=(values[:, :3] > 64).mean(axis=0).round(5).tolist(),
                            saturated_fraction=(values[:, :3] == 255).mean(axis=0).round(5).tolist()))
    values = np.concatenate(data)
    rows = [','.join(map(str, row.flatten())) for row in np.array_split(values, max(1, len(values) // 16))]
    header = ('// Generated by tools/analyze_reactivity.py; see music/reactivity.json.\n'
              '#pragma once\n#include <cstdint>\nnamespace remix::reactivity_data {\n'
              f'inline constexpr int rate={RATE}, count={len(values)};\n'
              'inline constexpr int offsets[]={'+','.join(map(str, offsets))+'};\n'
              'inline constexpr std::uint8_t values[]={\n'+',\n'.join(rows)+'\n};\n}\n')
    (root / 'src/music_reactivity.hpp').write_text(header, encoding='utf-8')
    report = dict(rate=RATE, channels=['low_attack', 'mid_attack', 'high_attack', 'low_onset_phase'],
                  method='Centered 2048-sample 48kHz Hann FFT; positive band flux minus local floor; independent peaks and exponential releases; no assumed BPM',
                  release_seconds=RELEASE, refractory_seconds=REFRACTORY, tracks=reports)
    (root / 'music/reactivity.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
